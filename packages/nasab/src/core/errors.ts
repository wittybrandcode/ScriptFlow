export class NasabError extends Error {
  public code: ErrorCode;
  public involvedNodes: string[];

  constructor(code: ErrorCode, message: string, involvedNodes: string[] = []) {
    super(message);
    this.name = 'NasabError';
    this.code = code;
    this.involvedNodes = involvedNodes;
  }
}
