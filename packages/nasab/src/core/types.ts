import { RelationType, Gender } from './enums';

export interface Person {
  id: string;
  name: string;
  gender: Gender;
  isDeceased: boolean;
  birthDate?: string;
  deathDate?: string;
  lineageId?: string; // ID assigned to a specific lineage cluster
  isLineageLocked?: boolean;
  lifecycle?: {
    birthEpisode?: number;
    deathEpisode?: number;
  };
  kunya?: string;       // اللقب العائلي (الهاشمي، القرشي، آل سعود...)
  nasab?: string;       // سلسلة النسب الكاملة (محمد بن عبدالله بن عبدالمطلب)
}

export type ValidationMode = 'ISLAMIC_LAW' | 'CIVIL_LAW_WESTERN' | 'MEDICAL_GENETICS' | 'DRAMATIC';

export interface Relation {
  sourceId: string;
  targetId: string;
  type: RelationType;
  isAutoGenerated?: boolean;
  isTaboo?: boolean; // Used to mark forbidden relations forced by narrative
}

export interface InferredRelation extends Relation {
  isAutoGenerated: true;
  /** FIX-10: سبب الاستنتاج — مثال: "عكس PARENT_MALE" أو "أبناء نفس الأب f1" */
  inferredVia?: string;
}

export interface ValidationResult {
  status: 'SUCCESS' | 'WARNING' | 'ERROR';
  error?: import('./errors').NasabError;
}

export interface ValidationOptions {
  maxWives?: number;
  allowSameSexMarriage?: boolean;
  minParentAgeGap?: number;
  allowPolygamy?: boolean;
  maxPregnancyYears?: number;
}
