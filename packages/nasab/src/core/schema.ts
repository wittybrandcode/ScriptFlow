import { z } from 'zod';
import { RelationType, Gender } from './enums';

export const GenderSchema = z.nativeEnum(Gender);

export const RelationTypeSchema = z.nativeEnum(RelationType);

export const PersonSchema = z.object({
  id: z.string().min(1, 'ID is required'),
  name: z.string().min(1, 'Name is required'),
  gender: GenderSchema,
  isDeceased: z.boolean().default(false),
  birthDate: z.string().optional(),
  deathDate: z.string().optional(),
  lineageId: z.string().optional(),
  isLineageLocked: z.boolean().optional(),
  lifecycle: z.object({
    birthEpisode: z.number().optional(),
    deathEpisode: z.number().optional(),
  }).optional(),
  kunya: z.string().optional(),
  nasab: z.string().optional(),
});

export const RelationSchema = z.object({
  sourceId: z.string().min(1, 'Source ID is required'),
  targetId: z.string().min(1, 'Target ID is required'),
  type: RelationTypeSchema,
  isAutoGenerated: z.boolean().optional(),
  isTaboo: z.boolean().optional(),
});

export const InferredRelationSchema = RelationSchema.extend({
  isAutoGenerated: z.literal(true),
  inferredVia: z.string().optional(),
});

export const GraphSchema = z.object({
  persons: z.array(PersonSchema),
  relations: z.array(RelationSchema),
});

export type ValidatedPerson = z.infer<typeof PersonSchema>;
export type ValidatedRelation = z.infer<typeof RelationSchema>;
export type ValidatedGraph = z.infer<typeof GraphSchema>;
