const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'docs', 'audit', '00_file_structure.md');

const IGNORE_DIRS = [
  'node_modules',
  '.git',
  'dist',
  'target',
  '.vscode',
  '.gemini',
  'build',
  'gen'
];

const IGNORE_FILES = [
  'package-lock.json',
  'Cargo.lock',
  'tsc_output.txt',
  'tsc_output2.txt',
  'index_css_output.txt',
  'index_css_output_new.txt'
];

function buildTree(dirPath, prefix = '') {
  let result = '';
  let items = [];
  try {
    items = fs.readdirSync(dirPath);
  } catch (err) {
    return result;
  }

  // Filter out ignored dirs/files
  items = items.filter(item => {
    const fullPath = path.join(dirPath, item);
    let stat;
    try {
      stat = fs.statSync(fullPath);
    } catch (e) {
      return false; // ignore broken symlinks or locked files
    }
    if (stat.isDirectory()) {
      return !IGNORE_DIRS.includes(item);
    } else {
      return !IGNORE_FILES.includes(item);
    }
  });

  // Sort directories first, then files alphabetically
  items.sort((a, b) => {
    const aPath = path.join(dirPath, a);
    const bPath = path.join(dirPath, b);
    const aIsDir = fs.statSync(aPath).isDirectory();
    const bIsDir = fs.statSync(bPath).isDirectory();
    if (aIsDir && !bIsDir) return -1;
    if (!aIsDir && bIsDir) return 1;
    return a.localeCompare(b);
  });

  items.forEach((item, index) => {
    const isLast = index === items.length - 1;
    const itemPath = path.join(dirPath, item);
    const isDir = fs.statSync(itemPath).isDirectory();

    const connector = isLast ? '└── ' : '├── ';
    const dirIndicator = isDir ? '/' : '';
    result += `${prefix}${connector}${item}${dirIndicator}\n`;

    if (isDir) {
      const newPrefix = prefix + (isLast ? '    ' : '│   ');
      result += buildTree(itemPath, newPrefix);
    }
  });

  return result;
}

function generateMarkdown() {
  console.log(`Scanning project structure at: ${ROOT_DIR}...`);
  const treeContent = buildTree(ROOT_DIR);
  
  const markdown = `# ScriptFlow Enterprise - File Structure Tree

This file is automatically generated by \`tooling/generate-tree.js\`. It provides a complete, atomic directory tree of the workspace to help guide analysis.

\`\`\`
${path.basename(ROOT_DIR)}/
${treeContent}\`\`\`
`;

  // Make sure output dir exists
  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, markdown, 'utf-8');
  console.log(`Markdown tree generated successfully at: ${OUTPUT_FILE}`);
}

generateMarkdown();
